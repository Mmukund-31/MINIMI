/**
 * Offline evaluation runner: `npm run eval`
 *
 * Runs every scenario in evals/scenarios.ts (deterministic, no network, no
 * API keys), aggregates metrics and writes evals/REPORT.md plus a JSON file
 * under evals/results/. Numbers in the report come only from this run.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { Category, Metrics, Outcome } from "./lib";
import { scenarios } from "./scenarios";

const here = dirname(fileURLToPath(import.meta.url));

interface Row {
  id: string;
  category: Category;
  description: string;
  outcome: Outcome;
}

const pct = (n: number, d: number) => (d === 0 ? "n/a" : `${((100 * n) / d).toFixed(1)}%`);

async function main() {
  const filter = process.argv.find((a) => a.startsWith("--only="))?.slice(7);
  const rows: Row[] = [];
  for (const s of scenarios.filter((x) => !filter || x.id.startsWith(filter))) {
    let outcome: Outcome;
    try {
      outcome = await s.run();
    } catch (err) {
      outcome = { pass: false, failures: [`threw: ${(err as Error).stack ?? err}`], metrics: { errored: true } };
    }
    rows.push({ id: s.id, category: s.category, description: s.description, outcome });
    process.stdout.write(`${outcome.pass ? "PASS" : "FAIL"}  ${s.id.padEnd(5)} ${s.description}\n${outcome.pass ? "" : outcome.failures.map((f) => `        - ${f}\n`).join("")}`);
  }

  // ── aggregate ────────────────────────────────────────────────────────
  const sum = (pick: (m: Metrics) => number | undefined) => rows.reduce((a, r) => a + (pick(r.outcome.metrics) ?? 0), 0);
  const ret = { tp: sum((m) => m.retrieval?.tp), fp: sum((m) => m.retrieval?.fp), fn: sum((m) => m.retrieval?.fn) };
  const chg = { tp: sum((m) => m.change?.tp), fp: sum((m) => m.change?.fp), fn: sum((m) => m.change?.fn), tn: sum((m) => m.change?.tn) };
  const date = { correct: sum((m) => m.date?.correct), total: sum((m) => m.date?.total) };
  const status = { correct: sum((m) => m.status?.correct), total: sum((m) => m.status?.total) };
  const cites = { valid: sum((m) => m.citations?.valid), total: sum((m) => m.citations?.total) };
  const planted = { total: sum((m) => m.evidence?.plantedFabrications), survived: sum((m) => m.evidence?.plantedSurvived) };
  const agentRows = rows.filter((r) => r.outcome.metrics.latencyMs !== undefined);
  const searchCalls = agentRows.map((r) => r.outcome.metrics.searchCalls ?? 0);
  const latencies = agentRows.map((r) => r.outcome.metrics.latencyMs ?? 0).sort((a, b) => a - b);
  const errored = rows.filter((r) => r.outcome.metrics.errored).length;
  const passed = rows.filter((r) => r.outcome.pass).length;

  const cats = [...new Set(rows.map((r) => r.category))];
  const perCat = cats.map((c) => {
    const rs = rows.filter((r) => r.category === c);
    return { c, n: rs.length, p: rs.filter((r) => r.outcome.pass).length };
  });

  const ranAt = new Date().toISOString();
  const md = [
    "# Offline evaluation report",
    "",
    `Generated by \`npm run eval\` on ${ranAt}. Deterministic: scripted model outputs + fixture search results, no network.`,
    "These numbers measure the **system's deterministic machinery** (temporal resolution, retrieval, ranking, validation, comparison, citation filtering, degradation) given known model outputs. They do **not** measure live model quality; see `docs/evaluation.md` for the live run.",
    "",
    `**${passed}/${rows.length} scenarios passed.**`,
    "",
    "## Per category",
    "",
    "| Category | Passed | Total |",
    "|---|---|---|",
    ...perCat.map((x) => `| ${x.c} | ${x.p} | ${x.n} |`),
    "",
    "## Metrics",
    "",
    "| Metric | Value | Basis |",
    "|---|---|---|",
    `| Memory retrieval precision | ${pct(ret.tp, ret.tp + ret.fp)} | conversations retrieved vs expected (${ret.tp} TP, ${ret.fp} FP) |`,
    `| Memory retrieval recall | ${pct(ret.tp, ret.tp + ret.fn)} | ${ret.fn} expected conversations missed |`,
    `| Date-resolution accuracy | ${pct(date.correct, date.total)} | ${date.correct}/${date.total} temporal cases exact (incl. ambiguity flag) |`,
    `| Comparison status accuracy | ${pct(status.correct, status.total)} | ${status.correct}/${status.total} expected statuses (changed / unchanged / uncertain / not comparable) |`,
    `| Change-detection precision | ${pct(chg.tp, chg.tp + chg.fp)} | "changed" predictions that were real (${chg.tp} TP, ${chg.fp} FP) |`,
    `| Change-detection recall | ${pct(chg.tp, chg.tp + chg.fn)} | real changes detected (${chg.fn} missed) |`,
    `| Citation correctness | ${pct(cites.valid, cites.total)} | ${cites.valid}/${cites.total} citations in final answers resolve to retrieved sources |`,
    `| Planted fabrications surviving validation | ${planted.survived}/${planted.total} | hallucinated source ids / non-verbatim quotes injected into model output |`,
    `| Search calls per request | avg ${(searchCalls.reduce((a, b) => a + b, 0) / Math.max(1, searchCalls.length)).toFixed(2)}, max ${Math.max(0, ...searchCalls)} | end-to-end scenarios |`,
    `| End-to-end latency (offline) | p50 ${latencies[Math.floor(latencies.length / 2)] ?? 0} ms, max ${latencies.at(-1) ?? 0} ms | pipeline overhead only, no network/model latency |`,
    `| Token consumption | n/a offline | scripted model; see live run |`,
    `| Unexpected error rate | ${pct(errored, rows.length)} | runs that threw when no error was expected |`,
    "",
    "## Scenarios",
    "",
    "| ID | Category | Scenario | Result |",
    "|---|---|---|---|",
    ...rows.map((r) => `| ${r.id} | ${r.category} | ${r.description.replace(/\|/g, "\\|")} | ${r.outcome.pass ? "pass" : `**FAIL**: ${r.outcome.failures.join("; ").replace(/\|/g, "\\|")}`} |`),
    "",
  ].join("\n");

  if (!filter) {
    writeFileSync(join(here, "REPORT.md"), md);
    mkdirSync(join(here, "results"), { recursive: true });
    writeFileSync(join(here, "results", "offline-latest.json"), JSON.stringify({ ranAt, rows }, null, 2));
  }
  process.stdout.write(`\n${passed}/${rows.length} passed. ${filter ? "" : "Report: evals/REPORT.md"}\n`);
  process.exitCode = passed === rows.length ? 0 : 1;
}

void main();
